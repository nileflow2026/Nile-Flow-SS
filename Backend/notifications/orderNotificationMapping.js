"use strict";

const { ORDER_EVENT_TYPE, ORDER_STATUS } = require("../orders/OrderTypes");
const { EVENT } = require("./NotificationTypes");

const EVENT_MAP = Object.freeze({
  [ORDER_EVENT_TYPE.CREATED]: EVENT.ORDER_CREATED,
  "order.cancelled": EVENT.ORDER_CANCELLED,
  [ORDER_EVENT_TYPE.CANCELLATION_APPROVED]: EVENT.ORDER_CANCELLATION_APPROVED,
  [ORDER_EVENT_TYPE.CANCELLATION_REQUESTED]: EVENT.ORDER_CANCELLATION_REQUESTED,
  [ORDER_EVENT_TYPE.CANCELLATION_REJECTED]: EVENT.ORDER_CANCELLATION_REJECTED,
});

const STATUS_EVENT_MAP = Object.freeze({
  [ORDER_STATUS.CONFIRMED]: EVENT.ORDER_CONFIRMED,
  [ORDER_STATUS.PREPARING]: EVENT.ORDER_PREPARING,
  [ORDER_STATUS.READY_FOR_DISPATCH]: EVENT.ORDER_READY,
  [ORDER_STATUS.OUT_FOR_DELIVERY]: EVENT.ORDER_OUT_FOR_DELIVERY,
  [ORDER_STATUS.DELIVERED]: EVENT.ORDER_DELIVERED,
  [ORDER_STATUS.CANCELLED]: EVENT.ORDER_CANCELLED,
});

function getOrderNotificationEvent(event, payload) {
  if (event === ORDER_EVENT_TYPE.STATUS_CHANGED) {
    return STATUS_EVENT_MAP[payload?.metadata?.toStatus];
  }
  return EVENT_MAP[event];
}

module.exports = { getOrderNotificationEvent };
